<#
.SYNOPSIS
    Creates the distributable zip of the Ymir UWP package (Xbox Dev Mode / Windows) from an existing build.

.DESCRIPTION
    Run scripts/uwp/build.ps1 first. This script takes the newest MSBuild package folder for the configuration and
    produces, under out/dist:

      ymir-uwp_<version>_x64.zip
        ymir-sdl3_<version>_x64[_Debug].msix     the app package (signed)
        ymir-sdl3_<version>_x64[_Debug].cer      signing certificate (PC installs need it trusted)
        Dependencies\x64\Microsoft.VCLibs*.appx  framework dependency (install it on Xbox together with the .msix)
        Install.ps1, Add-AppDevPackage.ps1, Add-AppDevPackage.resources\   PC installer generated by Visual Studio
        INSTALL.md                               installation instructions for Xbox and PC

      ymir-uwp_<version>_x64_symbols.zip         .appxsym debug symbols, for crash dump analysis

    The paths of both zips and the version are written to $env:GITHUB_OUTPUT when running in GitHub Actions
    (outputs: version, zip, symbols).

.PARAMETER Configuration
    Debug or Release; must match what was built.

.EXAMPLE
    pwsh scripts/uwp/package.ps1 -Configuration Release
#>
param(
    [ValidateSet('Debug', 'Release')][string]$Configuration = 'Release'
)

$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'common.ps1')

$pkg = Find-YmirUwpPackage -Configuration $Configuration
if (!$pkg) { throw "No package found; run scripts/uwp/build.ps1 -Configuration $Configuration first" }
if ($pkg.Dependencies.Count -eq 0) { throw "No dependency packages found in $($pkg.Dir)\Dependencies\x64" }

$suffix = if ($Configuration -eq 'Debug') { '_Debug' } else { '' }
$name = "ymir-uwp_$($pkg.Version)_x64$suffix"
$distRoot = Join-Path $YmirRoot 'out\dist'
$staging = Join-Path $distRoot $name
$zip = Join-Path $distRoot "$name.zip"
$symbolsZip = Join-Path $distRoot "${name}_symbols.zip"

New-Item -ItemType Directory -Path $distRoot -Force | Out-Null
if (Test-Path $staging) {
    # Only ever clears this script's own staging folder under out\dist
    Remove-Item -LiteralPath $staging -Recurse -Force
}
New-Item -ItemType Directory -Path (Join-Path $staging 'Dependencies\x64') -Force | Out-Null

Copy-Item $pkg.Msix.FullName $staging
if ($pkg.Certificate) { Copy-Item $pkg.Certificate.FullName $staging }
$pkg.Dependencies | Copy-Item -Destination (Join-Path $staging 'Dependencies\x64')
foreach ($installer in 'Install.ps1', 'Add-AppDevPackage.ps1', 'Add-AppDevPackage.resources') {
    $path = Join-Path $pkg.Dir $installer
    if (Test-Path $path) { Copy-Item $path $staging -Recurse }
}

$msixName = $pkg.Msix.Name
$depNames = ($pkg.Dependencies | ForEach-Object { "``Dependencies\x64\$($_.Name)``" }) -join ', '
@"
# Ymir UWP $($pkg.Version) (x64)

Sega Saturn emulator for Xbox Series X|S (Dev Mode) and Windows 10/11.

## Xbox (Dev Mode)

1. Open the Device Portal in a browser: ``https://<xbox-ip>:11443`` (Dev Home -> Remote Access settings).
2. *Home* -> *My games & apps* -> **Add** -> select ``$msixName`` -> **Next**.
3. Add the dependency $depNames -> **Start**.
4. In Dev Home, select the Ymir tile -> **View** button -> *View details* -> **App type: Game**.
   (The default "App" type limits the app to 1 GB of RAM and part of the GPU.)
5. BIOS: create a folder named ``Ymir`` at the root of an NTFS USB drive with ``roms\ipl\`` inside and copy the
   Saturn BIOS there. The drive needs permissions for UWP apps; on a PC, as admin:
   ``icacls E:\ /grant "*S-1-15-2-1:(OI)(CI)F" /T`` (replace ``E:`` with the drive letter).
   Without a USB ``Ymir`` folder, the profile is stored in the app's LocalState folder, reachable through the
   Device Portal file explorer: ``LocalAppData\<package family>\LocalState\StrikerX3\Ymir\``.
6. Launch Ymir from its tile. A USB keyboard and mouse are recommended for the menus for now.
7. Optional: Settings -> Video -> enable **Use hardware acceleration** (Direct3D 12 renderer).

Log file: ``LocalState\StrikerX3\Ymir\ymir-uwp.log``.

## Windows 10/11

1. Enable Developer Mode (Settings -> System -> For developers).
2. Right-click ``Install.ps1`` -> *Run with PowerShell*. It installs the certificate (asks for elevation), the
   dependencies and the app.
3. Launch Ymir from the Start menu.
"@ | Set-Content -Path (Join-Path $staging 'INSTALL.md') -Encoding utf8NoBOM

Compress-Archive -Path (Join-Path $staging '*') -DestinationPath $zip -Force
Write-Host "Distributable: $zip ($([math]::Round((Get-Item $zip).Length / 1MB, 2)) MB)" -ForegroundColor Green

if ($pkg.Symbols) {
    Compress-Archive -Path $pkg.Symbols.FullName -DestinationPath $symbolsZip -Force
    Write-Host "Symbols:       $symbolsZip" -ForegroundColor Green
}

if ($env:GITHUB_OUTPUT) {
    "version=$($pkg.Version)" | Out-File -FilePath $env:GITHUB_OUTPUT -Append -Encoding utf8
    "zip=$zip" | Out-File -FilePath $env:GITHUB_OUTPUT -Append -Encoding utf8
    if ($pkg.Symbols) { "symbols=$symbolsZip" | Out-File -FilePath $env:GITHUB_OUTPUT -Append -Encoding utf8 }
}
