<#
.SYNOPSIS
    Generates the Visual Studio solution for the UWP build (if needed) and opens it.

.DESCRIPTION
    Ymir is a CMake project: the .slnx/.vcxproj files are generated by CMake into out/build/<preset>/ and are not
    committed (they contain machine-specific absolute paths). This script:
    1. Builds the prebuilt dependencies (SDL3-uwp) if out/uwp-deps is missing.
    2. Runs the CMake configure step for the UWP preset (VS 2026 or the VS 2022 fallback).
    3. Opens out/build/<preset>/Ymir.slnx (or Ymir.sln with VS 2022) in Visual Studio.

    In Visual Studio, ymir-sdl3 is the startup project. Pick Debug or RelWithDebInfo + x64 and press F5 to deploy and
    run the UWP app on this PC (requires Windows Developer Mode). Re-run this script (or `cmake --preset ...`) after
    changing any CMakeLists.txt; Visual Studio then asks to reload the solution.

.PARAMETER VisualStudio
    auto (default: 2026 if installed, otherwise 2022), 2026 or 2022.

.PARAMETER NoOpen
    Only generate the solution; do not launch Visual Studio.

.EXAMPLE
    pwsh scripts/uwp/open-vs.ps1
#>
param(
    [ValidateSet('auto', '2026', '2022')][string]$VisualStudio = 'auto',
    [switch]$NoOpen
)

$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'common.ps1')

$toolchain = Resolve-YmirUwpToolchain -VisualStudio $VisualStudio
Write-Host "Using Visual Studio $($toolchain.VisualStudio), preset $($toolchain.Preset)" -ForegroundColor Cyan

Push-Location $YmirRoot
try {
    if (!(Test-Path (Join-Path $YmirRoot 'out\uwp-deps\bin\SDL3.dll'))) {
        & (Join-Path $PSScriptRoot 'build-deps.ps1') -VisualStudio $toolchain.VisualStudio
    }

    if (!(Test-Path (Join-Path $YmirRoot 'vcpkg\vcpkg.exe'))) {
        Write-Host '=== Bootstrapping vcpkg ===' -ForegroundColor Cyan
        & (Join-Path $YmirRoot 'vcpkg\bootstrap-vcpkg.bat') -disableMetrics
        if ($LASTEXITCODE -ne 0) { throw 'vcpkg bootstrap failed' }
    }

    Write-Host "=== Generating the solution ($($toolchain.Preset)) ===" -ForegroundColor Cyan
    cmake --preset $toolchain.Preset
    if ($LASTEXITCODE -ne 0) { throw 'CMake configure failed' }

    $solution = Get-ChildItem $toolchain.BuildDir -File |
        Where-Object { $_.Name -in 'Ymir.slnx', 'Ymir.sln' } | Select-Object -First 1
    if (!$solution) { throw "No Ymir.slnx/Ymir.sln found in $($toolchain.BuildDir)" }
    Write-Host "Solution: $($solution.FullName)" -ForegroundColor Green

    if (!$NoOpen) {
        # Prefer the devenv.exe of the selected Visual Studio version; fall back to the file association
        $range = if ($toolchain.VisualStudio -eq '2026') { '[18.0,19.0)' } else { '[17.0,18.0)' }
        $vswhere = Join-Path ${env:ProgramFiles(x86)} 'Microsoft Visual Studio\Installer\vswhere.exe'
        $devenv = & $vswhere -products * -version $range -find 'Common7\IDE\devenv.exe' | Select-Object -First 1
        if ($devenv) {
            Start-Process $devenv -ArgumentList "`"$($solution.FullName)`""
        } else {
            Write-Host 'devenv.exe not found (Build Tools only?); trying the .slnx/.sln file association' -ForegroundColor Yellow
            Start-Process $solution.FullName
        }
    }
} finally {
    Pop-Location
}
