const GlyphRows &GlyphFor(char32_t codePoint) {
    if (codePoint >= 0x20 && codePoint <= 0x7E) {
        return kAscii[codePoint - 0x20];
    }
    if (codePoint == 0x266Au || codePoint == 0x266Bu) {
        return kMusicNote;
    }
    return kMissing;
}

std::u32string Decode(std::string_view text) {
    std::u32string out;
    out.reserve(text.size());
    std::size_t i = 0;
    while (i < text.size()) {
        const auto lead = static_cast<unsigned char>(text[i]);
        int length = 0;
        char32_t codePoint = 0;
        if (lead < 0x80) {
            length = 1;
            codePoint = lead;
        } else if ((lead & 0xE0) == 0xC0) {
            length = 2;
            codePoint = lead & 0x1F;
        } else if ((lead & 0xF0) == 0xE0) {
            length = 3;
            codePoint = lead & 0x0F;
        } else if ((lead & 0xF8) == 0xF0) {
            length = 4;
            codePoint = lead & 0x07;
        } else {
            out.push_back(char32_t{0xFFFD});
            ++i;
            continue;
        }

        if (i + length > text.size()) {
            out.push_back(char32_t{0xFFFD});
            break;
        }
        bool valid = true;
        for (int k = 1; k < length; ++k) {
            const auto next = static_cast<unsigned char>(text[i + k]);
            if ((next & 0xC0) != 0x80) {
                valid = false;
                break;
            }
            codePoint = (codePoint << 6) | (next & 0x3F);
        }
        if (!valid) {
            out.push_back(char32_t{0xFFFD});
            ++i;
            continue;
        }
        out.push_back(codePoint);
        i += length;
    }
    return out;
}

int TextColumns(std::string_view text) {
    const std::size_t count = Decode(text).size();
    return count == 0 ? 0 : static_cast<int>(count) * kAdvance - 1;
}

